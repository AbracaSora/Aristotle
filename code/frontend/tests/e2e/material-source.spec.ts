import { expect, test } from "@playwright/test";
import path from "node:path";

test("PDF 经确认和授权后解释可追溯至原页，删除后停止检索", async ({page}, info) => {
  const title="线性序列的前驱";
  await page.goto("/");
  await page.getByRole("textbox",{name:"账号"}).fill("pdf-reader");
  await page.getByRole("textbox",{name:"密码"}).fill("demo-password");
  await page.getByRole("button",{name:/进入学习空间/}).click();
  await page.locator("#map-scope").click();
  await page.locator(".n-base-select-option").filter({hasText:"线性结构基础"}).click();
  const changed=page.waitForResponse(r=>r.url().endsWith("/learning-scope")&&r.request().method()==="PATCH");
  await page.getByRole("button",{name:"确认范围"}).click();
  expect((await changed).ok()).toBeTruthy();
  const materials=page.getByRole("button",{name:"我的资料",exact:true}).first();
  await materials.click();
  await page.locator(".import-panel .n-select").click();
  await page.getByText("文本型 PDF",{exact:true}).click();
  await page.getByRole("textbox",{name:"讲义标题"}).fill(title);
  await page.getByLabel("文本型 PDF",{exact:true}).setInputFiles(path.join(path.dirname(info.file),"fixtures","linear-notes.pdf"));
  await page.getByRole("button",{name:"建立导入任务"}).click();
  const chunk=page.locator(".chunk-panel").filter({hasText:title});
  await expect(chunk).toContainText("第 1 页");
  await expect(chunk).toContainText("one immediate predecessor");
  await chunk.getByRole("button",{name:"确认关联",exact:true}).click();
  await expect(chunk.getByRole("button",{name:"取消确认"})).toBeVisible();
  async function sources() {
    await page.getByRole("button",{name:"学习地图",exact:true}).first().click();
    await page.getByRole("button",{name:"线性结构与栈",exact:true}).click();
    await page.locator(".curriculum-node").filter({has:page.getByText("线性结构基础",{exact:true})}).getByRole("button").click();
    const sources=page.getByRole("region",{name:"相关资料与模型解释"});
    await sources.getByRole("textbox",{name:"资料检索问题"}).fill("predecessor");
    const response=page.waitForResponse(r=>r.url().includes("/retrieval/search")&&r.request().method()==="POST");
    await sources.getByRole("button",{name:"查找",exact:true}).click();
    expect((await response).ok()).toBeTruthy();
    return sources;
  }
  const explorer=await sources();
  const hit=explorer.locator(".source-hit").filter({hasText:title});
  await hit.locator("summary").click();
  await expect(hit).toContainText("第 1 页");
  await expect(hit.locator(".source-quote")).toContainText("one immediate predecessor");
  await expect(hit.getByText(/未授权发往模型/)).toBeVisible();
  await materials.click();
  const card=page.locator(".cards article").filter({hasText:title});
  const savedConsent=page.waitForResponse(r=>r.url().endsWith("/external-consent")&&r.request().method()==="PATCH");
  await card.getByRole("checkbox").click();
  expect((await savedConsent).ok()).toBeTruthy();
  const allowed=await sources();
  const explain=allowed.getByRole("button",{name:"基于所选来源解释"});
  await expect(explain).toBeDisabled();
  await allowed.getByRole("checkbox",{name:/允许将本次问题/}).click();
  await explain.click();
  const citation=allowed.locator(".answer-citation").filter({hasText:title});
  await citation.locator("summary").click();
  await expect(citation).toContainText("第 1 页");
  await expect(citation.locator(".source-quote")).toContainText("one immediate predecessor");
  await materials.click();
  await page.locator(".cards article").filter({hasText:title}).getByRole("button",{name:"删除",exact:true}).click();
  await page.locator(".n-popconfirm__action button").last().click();
  await expect(page.getByRole("heading",{name:title,exact:true})).toHaveCount(0);
  const after=await sources();
  await expect(after.locator(".source-hit").filter({hasText:title})).toHaveCount(0);
});
